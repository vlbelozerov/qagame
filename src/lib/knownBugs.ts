import type { Area, Severity } from './types';

/**
 * Тип эталонного дефекта. Самих данных здесь нет: список ответов лежит зашифрованным
 * в `secret/known-bugs.enc` (репозиторий публичный) и в приватном проекте Apps Script,
 * откуда админка получает его по паролю организатора.
 *
 * Расшифровать для правок: `QAGAME_SECRET="..." npm run reference:unlock`.
 */
export interface KnownBug {
  code: string;
  area: Area;
  severity: Severity;
  title: string;
  hint: string;
  /**
   * Группы ключевых слов для авторазбора. Группа считается сработавшей, если найдено
   * любое слово из неё; уверенное совпадение — когда сработали все группы дефекта.
   * Первая группа обычно называет объект, вторая — суть проблемы.
   */
  keywords: string[][];
}
