/**
 * Приманка для тех, кто снимает оверлей через инструменты разработчика.
 *
 * Закрытую витрину нельзя защитить по-настоящему: весь код исполняется в браузере
 * участника, и class="blur-[14px]" удаляется в один клик. Зато можно сделать так,
 * чтобы заглянувший выдал себя сам.
 *
 * Пока игра не идёт, магазин показывает подменённые промокоды. В рабочем магазине
 * их не существует, и увидеть их можно только со снятым оверлеем. Если такой код
 * всплывает в баг-репорте — участник не просто смотрел, а ещё и попробовал его
 * применить, получил «Промокод не найден» и завёл на это дефект.
 */

/** Промокоды-приманки: показываются на баннере, только пока витрина закрыта. */
export const HONEYPOT_CODES = ['PEEK50', 'GHOST99'] as const;

/** Дополнительные слова-маркеры, встречающиеся только в закрытой витрине. */
const HONEYPOT_MARKERS = [...HONEYPOT_CODES, 'предпросмотр витрины'];

/**
 * Упоминается ли приманка в тексте баг-репорта. Сравнение без регистра и с учётом
 * латинских подмен не нужно: коды и так набраны латиницей заглавными.
 */
export function mentionsHoneypot(text: string): string | null {
  const haystack = text.toLowerCase();
  return HONEYPOT_MARKERS.find((m) => haystack.includes(m.toLowerCase())) ?? null;
}
