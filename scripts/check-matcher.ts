let confident = 0;
let lowButRight = 0;
let missed = 0;
let wrong = 0;
let garbageOk = 0;
let garbageBad = 0;

for (const [text, expected] of CASES) {
  const m = matchReport(mk(text), KNOWN_BUGS);
  if (expected === '') {
    if (m.confidence === 'high') {
      garbageBad += 1;
      console.log(`  МУСОР ПРИНЯТ УВЕРЕННО: "${text}" -> ${m.code}`);
    } else {
      garbageOk += 1;
    }
    continue;
  }
  if (m.code === expected && m.confidence === 'high') confident += 1;
  else if (m.code === expected) {
    lowButRight += 1;
    console.log(`  неуверенно (но верно): "${text}" -> ${expected}`);
  } else if (m.code === '') {
    missed += 1;
    console.log(`  не распознано: "${text}" (ожидали ${expected})`);
  } else {
    wrong += 1;
    console.log(`  НЕВЕРНЫЙ КОД: "${text}" ожидали ${expected}, получили ${m.code} (${m.confidence})`);
  }
}

const total = CASES.filter(([, e]) => e !== '').length;
console.log(
  `\nуверенно верно: ${confident}/${total} | верно неуверенно: ${lowButRight} | ` +
    `не распознано: ${missed} | неверный код: ${wrong} | мусор отсеян: ${garbageOk}/${garbageOk + garbageBad}`,
);

const accuracy = confident / total;
if (wrong > 0 || garbageBad > 0) {
  console.error('\nПРОВАЛ: автомат присваивает неверные коды — правьте ключевые слова.');
  process.exit(1);
}
